package com.clawfare.db

import java.io.IOException
import java.nio.ByteBuffer
import java.nio.channels.FileChannel
import java.nio.charset.CodingErrorAction
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.LinkOption
import java.nio.file.Path
import java.nio.file.StandardOpenOption
import java.nio.file.attribute.PosixFileAttributeView
import java.nio.file.attribute.PosixFilePermissions
import java.sql.DriverManager

/**
 * Offline encrypted, authenticated SQLite backups.
 *
 * CLWDB002 uses independent authenticated AES-256-GCM records, each
 * explicitly verified before a recovered database can be published.
 * See AuthenticatedSqliteArchiveCodec for the versioned archive contract.
 *
 * Source DB snapshots are generated by SQLite VACUUM INTO to include committed
 * WAL records. The temporary plaintext SQLite file is confined to an owner-
 * only 0700 directory, but disk remnants are NOT securely erased.
 */
object EncryptedSqliteBackups {
    private const val MIN_PASSPHRASE_CHARS = 16
    private val privateFilePermissions = PosixFilePermissions.fromString("rw-------")
    private val privateDirectoryPermissions = PosixFilePermissions.fromString("rwx------")

    /** Read a secret without placing it on the command line or in shell history. */
    fun passphraseFromFile(file: Path): CharArray {
        requirePrivateRegularFile(file, "Passphrase")
        if (Files.size(file) !in 16L..4096L) {
            throw IOException("Passphrase file must contain 16 to 4096 UTF-8 bytes.")
        }
        val bytes = Files.readAllBytes(file)
        try {
            val decoder =
                StandardCharsets.UTF_8
                    .newDecoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT)
            val text = decoder.decode(ByteBuffer.wrap(bytes)).toString()
            val passphrase = text.removeSuffix("\n").removeSuffix("\r").toCharArray()
            if (passphrase.size < MIN_PASSPHRASE_CHARS) {
                passphrase.fill('\u0000')
                throw IOException("Passphrase must contain at least 16 characters.")
            }
            return passphrase
        } finally {
            bytes.fill(0)
        }
    }

    /**
     * Never overwrite an existing archive. Does not migrate the source
     * database or invoke the Clawfare CLI's automatic database initialization.
     */
    fun backup(
        source: Path,
        archive: Path,
        passphrase: CharArray,
    ) {
        requireStrongPassphrase(passphrase)
        requireRegularFile(source, "Source database")
        val output = normalize(archive)
        val parent = requirePrivateOutputParent(output)
        ensureAbsent(output, "Archive")
        withPrivateStaging(parent) { staging ->
            val plaintext = staging.resolve("snapshot.sqlite")
            val encrypted = staging.resolve("archive.enc")
            val sqlPath = plaintext.toString().replace("'", "''")
            DriverManager.getConnection("jdbc:sqlite:${normalize(source)}").use { connection ->
                connection.createStatement().use { statement ->
                    statement.execute("VACUUM INTO '$sqlPath'")
                }
            }
            Files.setPosixFilePermissions(plaintext, privateFilePermissions)
            verifyDatabase(plaintext)
            AuthenticatedSqliteArchiveCodec.encrypt(plaintext, encrypted, passphrase)
            Files.setPosixFilePermissions(encrypted, privateFilePermissions)
            forceToDisk(encrypted)
            ensureAbsent(output, "Archive")
            // Exclusive publication: never follow a destination symlink or
            // replace an existing backup, even if it appeared during writing.
            Files.createLink(output, encrypted)
        }
    }

    /**
     * Restore only into a NEW file, never the active database. No migrations
     * run during recovery; the caller can inspect the recovered old version.
     */
    fun restore(
        archive: Path,
        destination: Path,
        passphrase: CharArray,
    ) {
        requireStrongPassphrase(passphrase)
        requireRegularFile(archive, "Encrypted archive")
        val output = normalize(destination)
        val parent = requirePrivateOutputParent(output)
        ensureEmptyRestoreTarget(output)
        withPrivateStaging(parent) { staging ->
            val plaintext = staging.resolve("restored.sqlite")
            AuthenticatedSqliteArchiveCodec.decrypt(archive, plaintext, passphrase)
            Files.setPosixFilePermissions(plaintext, privateFilePermissions)
            verifyDatabase(plaintext)
            forceToDisk(plaintext)
            ensureEmptyRestoreTarget(output)
            Files.createLink(output, plaintext)
        }
    }

    /**
     * Rotate the passphrase on an existing CLWDB002 archive without touching
     * the live database or modifying the source archive. Decryption, SQLite
     * integrity validation and re-encryption all happen inside a private
     * temporary directory. Publication is exclusive and requires a new path.
     *
     * This does not revoke previous archives or securely erase their keys.
     */
    fun rekey(
        archive: Path,
        newArchive: Path,
        oldPassphrase: CharArray,
        newPassphrase: CharArray,
    ) {
        requireStrongPassphrase(oldPassphrase)
        requireStrongPassphrase(newPassphrase)
        if (oldPassphrase.contentEquals(newPassphrase)) {
            throw IOException("New archive passphrase must differ from the previous passphrase.")
        }
        requireRegularFile(archive, "Encrypted archive")
        val output = normalize(newArchive)
        val parent = requirePrivateOutputParent(output)
        ensureAbsent(output, "New encrypted archive")
        withPrivateStaging(parent) { staging ->
            val plaintext = staging.resolve("rekey.sqlite")
            val encrypted = staging.resolve("rekey.clwdb")
            AuthenticatedSqliteArchiveCodec.decrypt(archive, plaintext, oldPassphrase)
            Files.setPosixFilePermissions(plaintext, privateFilePermissions)
            verifyDatabase(plaintext)
            AuthenticatedSqliteArchiveCodec.encrypt(plaintext, encrypted, newPassphrase)
            Files.setPosixFilePermissions(encrypted, privateFilePermissions)
            forceToDisk(encrypted)
            ensureAbsent(output, "New encrypted archive")
            // A hard link publishes the already verified encrypted bytes without
            // clobbering any archive installed by another process in the meantime.
            Files.createLink(output, encrypted)
        }
    }

    private fun verifyDatabase(path: Path) {
        DriverManager.getConnection("jdbc:sqlite:${normalize(path)}").use { connection ->
            connection.createStatement().use { statement ->
                statement.executeQuery("PRAGMA integrity_check").use { rows ->
                    if (!rows.next() || rows.getString(1) != "ok" || rows.next()) {
                        throw IOException("Recovered SQLite database failed integrity check.")
                    }
                }
            }
        }
    }

    private fun requireStrongPassphrase(passphrase: CharArray) {
        if (passphrase.size < MIN_PASSPHRASE_CHARS) {
            throw IOException("Passphrase must contain at least 16 characters.")
        }
    }

    private fun normalize(path: Path): Path = path.toAbsolutePath().normalize()

    private fun requireRegularFile(
        path: Path,
        label: String,
    ) {
        if (!Files.isRegularFile(path, LinkOption.NOFOLLOW_LINKS)) {
            throw IOException("$label must be an existing regular file (not a symlink).")
        }
    }

    private fun requirePrivateRegularFile(
        path: Path,
        label: String,
    ) {
        requireRegularFile(path, label)
        val permissions =
            runCatching { Files.getPosixFilePermissions(path, LinkOption.NOFOLLOW_LINKS) }
                .getOrElse { throw IOException("$label requires POSIX owner-only file permissions.", it) }
        if (permissions.any { permission -> permission.name.startsWith("GROUP_") || permission.name.startsWith("OTHERS_") }) {
            throw IOException("$label file must not be readable or writable by group or others.")
        }
    }

    private fun requirePrivateOutputParent(destination: Path): Path {
        val parent = destination.parent ?: throw IOException("Output must have a parent directory.")
        if (!Files.isDirectory(parent, LinkOption.NOFOLLOW_LINKS) ||
            Files.getFileAttributeView(parent, PosixFileAttributeView::class.java) == null
        ) {
            throw IOException("Output parent must be an existing non-symlink POSIX directory.")
        }
        return parent
    }

    private fun ensureAbsent(
        path: Path,
        label: String,
    ) {
        if (Files.exists(path, LinkOption.NOFOLLOW_LINKS)) {
            throw IOException("$label already exists; refusing to overwrite it.")
        }
    }

    private fun ensureEmptyRestoreTarget(destination: Path) {
        ensureAbsent(destination, "Recovery destination")
        for (suffix in listOf("-wal", "-shm", "-journal")) {
            ensureAbsent(destination.resolveSibling(destination.fileName.toString() + suffix), "Recovery sidecar")
        }
    }

    private inline fun withPrivateStaging(
        parent: Path,
        action: (Path) -> Unit,
    ) {
        val staging =
            Files.createTempDirectory(
                parent,
                ".clawfare-archive-",
                PosixFilePermissions.asFileAttribute(privateDirectoryPermissions),
            )
        try {
            action(staging)
        } finally {
            // These files are created only by this operation. The directory is
            // owner-only; cleaning up is not a guarantee of secure erasure.
            Files.list(staging).use { entries ->
                entries.forEach { entry -> Files.deleteIfExists(entry) }
            }
            Files.deleteIfExists(staging)
        }
    }

    private fun forceToDisk(path: Path) {
        FileChannel.open(path, StandardOpenOption.WRITE).use { it.force(true) }
    }
}
