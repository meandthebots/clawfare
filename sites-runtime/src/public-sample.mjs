// The only data admitted here is the bundled, PUBLIC Florida sample ResultSet.
// This is intentionally separate from tenant-specific investigations.
export const PUBLIC_SAMPLE_SLUG = "florida-dec-2026";
const MAX_FIXTURE_BYTES = 512 * 1024;
const SECRET_KEYS = /^(?:tokens?|api[-_]?keys?|access[-_]?tokens?|booking[-_]?tokens?|departure[-_]?tokens?|secret|password|authorization)$/i;

export const UPSERT_PUBLIC_SAMPLE_SQL = [
  "INSERT INTO public_sample_fixtures (slug, result_json, content_sha256, imported_at)",
  "VALUES (?, ?, ?, ?)",
  "ON CONFLICT(slug) DO UPDATE SET",
  "  result_json = excluded.result_json,",
  "  content_sha256 = excluded.content_sha256,",
  "  imported_at = excluded.imported_at",
].join("\n");

export const GET_PUBLIC_SAMPLE_SQL = [
  "SELECT result_json, content_sha256 FROM public_sample_fixtures WHERE slug = ?",
].join("\n");

function denySecrets(value, depth = 0) {
  if (depth > 24) throw new Error("Public fixture is too deeply nested.");
  if (Array.isArray(value)) {
    for (const item of value) denySecrets(item, depth + 1);
  } else if (value && typeof value === "object") {
    for (const [key, child] of Object.entries(value)) {
      if (SECRET_KEYS.test(key)) throw new Error("Private provider data is forbidden in the public fixture.");
      denySecrets(child, depth + 1);
    }
  }
}

export function validatePublicSample(sample) {
  if (!sample || typeof sample !== "object" || Array.isArray(sample) ||
      sample.id !== PUBLIC_SAMPLE_SLUG || typeof sample.title !== "string" ||
      sample.currency !== "GBP" || !Array.isArray(sample.itineraries) ||
      sample.itineraries.length === 0 || !Array.isArray(sample.addons) ||
      !Array.isArray(sample.vendors)) {
    throw new Error("Not the bundled public Kotlin ResultSet fixture.");
  }
  for (const item of [...sample.itineraries, ...sample.addons]) {
    if (!item || item.source !== "sample" || item.sourceLabel !== "sample" ||
        item.livePrice !== false || typeof item.id !== "string") {
      throw new Error("Public fixtures must contain sample-only, non-live itineraries.");
    }
  }
  denySecrets(sample);
  const serialized = JSON.stringify(sample);
  if (new TextEncoder().encode(serialized).length > MAX_FIXTURE_BYTES) {
    throw new Error("Public sample exceeds D1 snapshot size limit.");
  }
  return serialized;
}

async function sha256(text, cryptoApi) {
  const bytes = new Uint8Array(await cryptoApi.subtle.digest("SHA-256", new TextEncoder().encode(text)));
  return Array.from(bytes, value => value.toString(16).padStart(2, "0")).join("");
}

/**
 * Administrative bootstrap ONLY: must be invoked from trusted provisioning,
 * never an HTTP POST. The JSON input must be generated by the Kotlin
 * "report sample-json" CLI command from the public bundled fixtures.
 */
export async function bootstrapPublicSample(
  db, sample, { cryptoApi = globalThis.crypto, clock = () => new Date() } = {},
) {
  if (!db?.prepare) throw new TypeError("D1 binding required.");
  const json = validatePublicSample(sample);
  const digest = await sha256(json, cryptoApi);
  const now = clock();
  if (!(now instanceof Date) || !Number.isFinite(now.getTime())) {
    throw new Error("Invalid server UTC clock.");
  }
  await db.prepare(UPSERT_PUBLIC_SAMPLE_SQL)
    .bind(PUBLIC_SAMPLE_SLUG, json, digest, now.toISOString()).run();
  return digest;
}

export async function loadPublicSample(db, { cryptoApi = globalThis.crypto } = {}) {
  if (!db?.prepare) throw new TypeError("D1 binding required.");
  const row = await db.prepare(GET_PUBLIC_SAMPLE_SQL).bind(PUBLIC_SAMPLE_SLUG).first();
  if (!row) return null;
  if (typeof row.result_json !== "string" ||
      typeof row.content_sha256 !== "string" ||
      (await sha256(row.result_json, cryptoApi)) !== row.content_sha256) {
    throw new Error("Stored public sample digest mismatch; refusing to serve.");
  }
  const parsed = JSON.parse(row.result_json);
  validatePublicSample(parsed);
  return parsed;
}
